from copy import deepcopy


def seg(weight, **values):
    return {"weight": weight, "values": values}


def dim(name, **extra):
    payload = {"name": name}
    payload.update(extra)
    return payload


def field(name, field_type, params=None):
    payload = {"name": name, "type": field_type}
    if params is not None:
        payload["params"] = params
    return payload


def sex_name_field(name="first_name"):
    return field(
        name,
        "faker_from_segment",
        {
            "segment_key": "sex",
            "providers": {"M": "first_name_male", "F": "first_name_female"},
            "fallback_provider": "first_name",
        },
    )


def birth_date_field():
    return field(
        "birth_date",
        "birth_date_from_age_band",
        {"segment_key": "age_band", "reference_date": "2023-01-01", "default_max_age": 105},
    )


def belgian_address_fields(*, profile="home_address", region_segment_key="region", region=None, province=None, postcode_prefix=None):
    params = {"profile": profile}
    if region is None and region_segment_key is not None:
        params["region_segment_key"] = region_segment_key
    if region is not None:
        params["region"] = region
    if province is not None:
        params["province"] = province
    if postcode_prefix is not None:
        params["postcode_prefix"] = postcode_prefix
    return [
        field("street_address", "belgian_address_component", {**params, "component": "street_address"}),
        field("postcode", "belgian_address_component", {**params, "component": "postcode"}),
        field("city", "belgian_address_component", {**params, "component": "city"}),
    ]


def base_config(seed, records, segments, dimensions, fields, *, scope, locale="nl_BE", filters=None):
    population_model = {
        "scope": scope,
        "dimensions": dimensions,
        "segments": segments,
    }
    if filters:
        population_model["filters"] = filters
    return {
        "version": "1.0",
        "locale": locale,
        "seed": seed,
        "records": records,
        "population_model": population_model,
        "fields": fields,
    }


